// کاربردها:
// جی‌سان: رایج‌ترین قالب در ای‌پی‌آی‌ها، اپلیکیشن‌های موبایل و فایل‌های تنظیمات
// ایکس‌ام‌ال: فایل‌های تنظیمات، سرویس‌های قدیمی، فید خبری و فایل‌های آفیس

// تفاوت‌ها:
