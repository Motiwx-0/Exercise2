// تمرین ۴: URL

// URL چیست؟

// یو‌آر‌ال یا مکان‌یاب یکتای منبع، آدرس کامل یک منبع در اینترنت است
// (مثل صفحه، تصویر یا فایل). مرورگر با آن می‌فهمد به کدام سرور وصل شود
// و چه چیزی درخواست کند.

// اجزای یک آدرس:
// - پروتکل:        پروتکلی که قانون ارتباط را مشخص می‌کند (مثل اچ‌تی‌تی‌پی‌اس)
// - زیردامنه:      بخش قبل از دامنه‌ی اصلی (مثل دبلیو دبلیو دبلیو)
// - دامنه:         نام سایت (مثل گوگل)
// - پسوند:         نوع یا کشور دامنه (مثل دات کام)
// - پورت:       شماره‌ی سرویس روی سرور (معمولاً پنهان است)
// - مسیر:          محل منبع داخل سایت
// - کوئری استرینگ: پارامترهای ارسالی به سرور به شکل کلید و مقدار
// - قطعه:       پرش به بخش مشخصی از صفحه


//                تمرین ۵: GET و POST


// گت چیست؟
// درخواست دریافت اطلاعات از سرور. پارامترها داخل خود آدرس قرار می‌گیرند

// پست چیست؟
// درخواست ارسال اطلاعات به سرور برای ثبت یا ایجاد
// داده‌ها داخل بدنه‌ی درخواست ارسال می‌شوند، نه آدرس

// تفاوت‌های گت و پست:

// - هدف:    گت گرفتن داده است             پست فرستادن داده
// - محل داده:    گت داخل آدرس است            پست داخل بدنه
// - دیده شدن:     گت در آدرس دیده می‌شود       پست دیده نمی‌شود
// - محدودیت حجم:    گت دارد                      پست تقریباً ندارد
// - بوکمارک:     گت قابل ذخیره است           پست قابل ذخیره نیست

// گت برای چه کارهایی استفاده می‌شود؟
// نمایش صفحه، جستجو، فیلتر کردن لیست محصولات، دریافت اطلاعات یک آیتم.

// پست برای چه کارهایی استفاده می‌شود؟
// ورود و ثبت‌نام، ارسال فرم، ثبت سفارش، آپلود فایل.

// مثال‌های واقعی:
// گت در وب‌سایت: جستجو در گوگل که عبارت جستجو داخل آدرس دیده می‌شود.
// گت در ای‌پی‌آی: دریافت اطلاعات محصول شماره ۵ از سرور.
// پست در وب‌سایت: فرم ورود که رمز عبور داخل بدنه ارسال می‌شود.
// پست در ای‌پی‌آی: ثبت سفارش جدید با ارسال اطلاعات در بدنه.

// نکته: پست به تنهایی امن‌تر نیست و فقط داده را از آدرس پنهان می‌کند.
// رمزنگاری واقعی کار اچ‌تی‌تی‌پی‌اس است.


