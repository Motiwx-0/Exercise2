// و انتقال داده به شکل جفت‌های کلید و مقدار است.

// ایکس‌ام‌ال چیست؟
// ایکس‌ام‌ال یا زبان نشانه‌گذاری توسعه‌پذیر، قالبی متنی بر پایه‌ی
